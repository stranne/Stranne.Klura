import 'dart:io';

import 'package:klura/puzzles/logjam/logic/logjam_generator.dart';
import 'package:klura/puzzles/logjam/logic/logjam_text.dart';

/// Finds the Hard Logjam puzzles that Klura ships, one for each day, and
/// writes them to [_output].
///
/// Puzzles of Hard's 20 moves or more take too long to find on a phone, so
/// this script finds them ahead of time with Klura's own generator and Hard's
/// configuration, from the keys `logjam-hard-set:1`, `logjam-hard-set:2` and
/// so on, skipping a key whose attempts all fail and a puzzle found before.
/// The same count always gives the same puzzles in the same order. Run it
/// from the repository root:
///
/// ```sh
/// dart run tool/find_logjam_puzzles.dart [count]
/// ```
///
/// A new set changes the Hard puzzle of existing days, so increase
/// `logjamGeneratorVersion` with it. The days use the puzzles in order and
/// start over after the last, so add puzzles before the set runs out.
void main(List<String> arguments) {
  final count = arguments.isEmpty ? 731 : int.parse(arguments.first);
  final config = LogjamLevel.hard.config;
  final found = <(String, int)>[];
  final seen = <String>{};
  final stopwatch = Stopwatch()..start();

  for (var key = 1; found.length < count; key++) {
    final GeneratedLogjam generated;
    try {
      generated = generateLogjam('logjam-hard-set:$key', config);
      // The generator gives up on a key after its attempts all fail, and
      // the next key is as good.
      // ignore: avoid_catching_errors
    } on StateError {
      continue;
    }
    final text = formatLogjam(generated.puzzle).trimRight().replaceAll(
      '\n',
      '/',
    );
    if (seen.add(text)) {
      found.add((text, generated.fewestMoves));
    }
    if (found.length % 50 == 0) {
      stdout.writeln(
        '${found.length} of $count puzzles, '
        '${stopwatch.elapsed.inSeconds} s',
      );
    }
  }

  final output = StringBuffer()
    ..writeln('// Generated by tool/find_logjam_puzzles.dart. Do not edit by')
    ..writeln('// hand: run the script, and increase logjamGeneratorVersion')
    ..writeln('// with a new set.')
    ..writeln()
    ..writeln(
      '/// The Hard puzzles, one for each day from `logjamFirstDay`, each',
    )
    ..writeln('/// in the text notation of `parseLogjam` with `/` between rows')
    ..writeln('/// and followed by the fewest moves it needs.')
    ..writeln('const List<String> logjamHardPuzzles = [');
  for (final (text, moves) in found) {
    output.writeln("  '$text', // $moves");
  }
  output.writeln('];');
  File(_output).writeAsStringSync(output.toString());

  final byMoves = <int, int>{};
  for (final (_, moves) in found) {
    byMoves[moves] = (byMoves[moves] ?? 0) + 1;
  }
  stdout
    ..writeln('Wrote ${found.length} puzzles to $_output')
    ..writeln(
      'Fewest moves: ${[
        for (final moves in byMoves.keys.toList()..sort()) '$moves: ${byMoves[moves]}',
      ].join(', ')}',
    )
    ..writeln('Took ${stopwatch.elapsed.inSeconds} s');
}

const String _output = 'lib/puzzles/logjam/logic/logjam_hard_puzzles.dart';
